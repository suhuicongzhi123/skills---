#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
宿主 hook 平台转变器（兼容层 · v6.1.0）

解决的问题：`.claude/` 只被 Claude Code 识别，国内 agent 平台安装技能时忽略该目录。
本脚本把 host-hooks.yaml 声明的 hook 语义**转变**为目标平台可用的形式：

  ① 事件钩子型平台（claude-code）→ 生成 .claude/settings.json（宿主强制，与仓库根等价）
  ② 规则常驻型平台（trae/qoder/codebuddy/kimi-code 等）→ 在平台规则目录生成规则文件
     （强制力降级为「规则常驻＋AI 自律」，生成物内显式声明降级）
  ③ 未核实平台（generic/未知）→ 输出规范摘要＋人工注册指引＋降级声明，不假装注册成功

用法：
  python scripts/install-host-hooks.py --list
  python scripts/install-host-hooks.py --detect --project-dir <项目目录>
  python scripts/install-host-hooks.py --platform trae --project-dir <项目目录>          # 预览（dry-run）
  python scripts/install-host-hooks.py --platform trae --project-dir <项目目录> --yes    # 执行写入
  python scripts/install-host-hooks.py --platform trae --project-dir <项目目录> --remove # 卸载生成物

设计约束：
  - 幂等：重复 --yes 覆盖生成物（内容确定性，覆盖前打印 diff 摘要）
  - 只写「本脚本生成物」，❌ 不改平台已有文件；--remove 只删自己的生成物
  - Windows 兼容：全部 UTF-8 读写（本库 E-017 教训）
  - 未核实平台注册格式时 **不猜测写入**——只输出指引（exit 3），防止伪实现
"""
import argparse
import json
import os
import sys

try:
    import yaml
except ImportError:
    print("FAIL 需要 PyYAML：pip install pyyaml")
    sys.exit(2)

DEFAULT_SKILL_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

GENERATED_MARK = "<!-- GENERATED by novel-amputee-writing/scripts/install-host-hooks.py -->"

# 规则常驻型平台：目录形态表（verified: false 的按此生成，生成物内含核对声明）
RULE_PLATFORMS = {
    "trae":       {"dir": ".trae",       "file": "novel-amputee-hooks.md", "label": "TRAE"},
    "qoder":      {"dir": ".qoder",       "file": "novel-amputee-hooks.md", "label": "Qoder"},
    "codebuddy":  {"dir": ".codebuddy",   "file": "novel-amputee-hooks.md", "label": "CodeBuddy"},
    "kimi-code":  {"dir": ".kimi",        "file": "novel-amputee-hooks.md", "label": "Kimi Code"},
}

# 平台探测（按项目目录中已知配置目录的存在性）
DETECT_ORDER = [
    (".claude", "claude-code"),
    (".trae", "trae"),
    (".qoder", "qoder"),
    (".codebuddy", "codebuddy"),
    (".kimi", "kimi-code"),
]


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def _norm(text):
    """行尾归一（\\r\\n → \\n）：卸载判定比「内容相等」时免疫 CRLF/LF 漂移（E-017 同思路）"""
    return text.replace("\r\n", "\n")


def load_spec(skill_root):
    p = os.path.join(skill_root, "host-hooks.yaml")
    if not os.path.isfile(p):
        print(f"FAIL 未找到 {p}")
        sys.exit(2)
    return yaml.safe_load(read(p)) or {}


def detect_platform(project_dir):
    found = []
    for d, name in DETECT_ORDER:
        if os.path.isdir(os.path.join(project_dir, d)):
            found.append(name)
    return found



def build_rule_file(platform_label):
    hard_rel = "novel-amputee-writing/rules/hard-layer.md"
    lines = [
        GENERATED_MARK,
        f"# novel-amputee-writing 宿主 hook 规则（{platform_label} 规则常驻形态）",
        "",
        "> 本文件由 install-host-hooks.py 从 host-hooks.yaml 转变生成（v6.1.0）。",
        "> **强制力降级声明**：原设计为宿主事件钩子（宿主强制）；本平台无已核实的事件钩子，",
        "> 转变为规则常驻＋AI 自律——**硬层驱逐风险回到「压缩/长会话后可能丢失」**，",
        "> 每章开写前重读硬层是最低补偿。平台目录形态未经官方实测，注册前请按平台文档核对。",
        "",
        "## 1. 硬约束常驻层（会话开始＋每章开写前）",
        "",
        f"- 整段读取并保持于上下文：`{hard_rel}`",
        "- ❌ 禁止摘要、禁止参与语义检索或相似度裁剪；每章开写前重读一次（防压缩驱逐）",
        "",
        "## 2. 本章规则包展开（每章开写前）",
        "",
        "- 有 shell：`python novel-amputee-writing/scripts/query_rules.py --genre <题材> --type <类型> --tier <尺度档> --mode <模式> --chapter-kind <章型> --conflict <冲突强度档> --chapter <N> --format text`",
        "- 无 shell：宿主预先运行上述命令（--format text），把产物拼进 system prompt",
        "- 参数取自小说项目账本；产物写入项目目录，❌ 不得写入技能目录",
        "",
        "## 3. 交付闸四链（每次交付／commit 前）",
        "",
        "- `python novel-amputee-writing/scripts/selfcheck.py`",
        "- `python novel-amputee-writing/scripts/compile_rules.py`",
        "- `python novel-amputee-writing/scripts/state_machine.py --ledger <项目账本> --check`",
        "- `python novel-amputee-writing/scripts/gatecheck.py <项目目录> --chapter N`",
        "- 任一 FAIL：不得交付、不得 commit；修复后重跑直至全 PASS",
        "",
        "## 4. 红队验证（pro/max 章末）",
        "",
        "- 按 `novel-amputee-writing/templates/redteam-brief.md` 执行；输入隔离，禁止自证「自查未发现」",
        "- 无真独立子代理 ⇒ 独立性声明作废，质量等级降为「自审」（写进账本工作流执行日志）",
        "",
        f"（规范源：host-hooks.yaml；卸载本文件：install-host-hooks.py --platform <平台> --remove）",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description="宿主 hook 平台转变器")
    ap.add_argument("--skill-root", default=DEFAULT_SKILL_ROOT)
    ap.add_argument("--project-dir", default=os.getcwd())
    ap.add_argument("--platform", default=None,
                    help="claude-code / trae / qoder / codebuddy / kimi-code / generic")
    ap.add_argument("--list", action="store_true", help="列出支持的平台")
    ap.add_argument("--detect", action="store_true", help="探测项目目录的宿主平台")
    ap.add_argument("--yes", action="store_true", help="执行写入（默认 dry-run 预览）")
    ap.add_argument("--remove", action="store_true", help="卸载本脚本生成物")
    a = ap.parse_args()

    skill_root = os.path.abspath(a.skill_root)
    project = os.path.abspath(a.project_dir)
    spec = load_spec(skill_root)

    if a.list:
        print("支持的平台：")
        print("  claude-code  事件钩子型（宿主强制，生成 .claude/settings.json）——verified")
        for k, v in RULE_PLATFORMS.items():
            print(f"  {k:<12} 规则常驻型（生成 {v['dir']}/{v['file']}，强制力降级显式声明）——格式未实测")
        print("  generic      未核实平台（输出人工注册指引，不写入）")
        return 0

    if a.detect:
        found = detect_platform(project)
        print(f"项目目录 {project} 探测结果：")
        if not found:
            print("  未发现已知平台配置目录（.claude/.trae/.qoder/.codebuddy/.kimi）")
            print("  可用 --platform 显式指定，或按平台文档人工注册（host-hooks.yaml）")
        else:
            for name in found:
                print(f"  发现 {name} 配置目录")
        return 0

    platform = a.platform
    if not platform:
        found = detect_platform(project)
        if len(found) == 1:
            platform = found[0]
            print(f"（自动探测：{platform}）")
        else:
            print("FAIL 未指定 --platform 且无法唯一探测；用 --list 查看支持项，或 --detect 查看探测结果")
            return 1

    # ── claude-code：事件钩子（与仓库根 .claude/ 等价）──
    if platform == "claude-code":
        target = os.path.join(project, ".claude", "settings.json")
        payload = {
            "hooks": {
                "SessionStart": [
                    {"hooks": [
                        {"type": "command",
                         "command": 'cat "${CLAUDE_PROJECT_DIR}/novel-amputee-writing/rules/hard-layer.md"'}
                    ]}
                ]
            }
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
        banner = f"[claude-code] 生成 {target}（SessionStart 硬层注入，宿主强制；与技能仓库根 .claude/ 等价）"
        return emit(target, content, banner, a.yes, a.remove)

    # ── 规则常驻型平台 ──
    if platform in RULE_PLATFORMS:
        cfg = RULE_PLATFORMS[platform]
        target = os.path.join(project, cfg["dir"], cfg["file"])
        content = build_rule_file(cfg["label"])
        banner = (f"[{platform}] 生成 {target}（规则常驻形态——强制力降级：宿主强制 → 规则常驻＋AI 自律，"
                  f"生成物内已显式声明；目录形态未经官方实测，注册前按平台文档核对）")
        return emit(target, content, banner, a.yes, a.remove)

    # ── 未核实平台：不猜测写入 ──
    print(f"[{platform}] 该平台注册形式未核实——不猜测写入（防伪实现）。")
    print("人工注册指引（规范源：novel-amputee-writing/host-hooks.yaml）：")
    for h in spec.get("hooks") or []:
        detail = (h.get("file") or h.get("command") or h.get("commands") or h.get("brief"))
        print(f"  - {h.get('id')}：{h.get('events')} → {h.get('action')} ({detail})")
    print("降级声明（写入账本·工作流执行日志）：")
    print("  「宿主 hook 未注册（平台形式未核实）：硬层常驻降级为每章开写前 AI 自读；"
          "交付闸降级为 AI 自跑＋用户抽核；独立性声明按平台子代理能力实判」")
    return 3


def emit(target, content, banner, yes, remove):
    if remove:
        if os.path.isfile(target):
            with open(target, encoding="utf-8", errors="replace") as f:
                old = f.read()
            # JSON 生成物（claude-code）无法携带注释标记——按「与本脚本确定性产物逐字节相等」判定；
            # 相等 ⇒ 本脚本生成物可安全卸载；不等 ⇒ 可能是用户手写配置，跳过不删（防误删）
            if GENERATED_MARK in old or _norm(old) == _norm(content):
                os.remove(target)
                print(f"已卸载 {target}")
                return 0
            print(f"跳过 {target}：非本脚本生成物（无生成标记且内容不匹配），不删除")
            return 0
        print(f"无需卸载：{target} 不存在")
        return 0

    print(banner)
    if os.path.isfile(target):
        with open(target, encoding="utf-8", errors="replace") as f:
            old = f.read()
        if old == content:
            print("  内容与现有文件一致（幂等，无需写入）")
            return 0
        print("  ⚠ 目标已存在且内容不同，将覆盖：")
        print(f"    旧 {len(old)} 字符 → 新 {len(content)} 字符")
    if not yes:
        print("  [dry-run] 预览模式，未写入。加 --yes 执行。")
        preview = content[:600]
        print("  ---- 生成物预览（前 600 字符）----")
        for l in preview.splitlines()[:24]:
            print("  | " + l)
        print("  ---- 预览结束 ----")
        return 0
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"  已写入 {target}（{len(content)} 字符）")
    return 0


if __name__ == "__main__":
    sys.exit(main())